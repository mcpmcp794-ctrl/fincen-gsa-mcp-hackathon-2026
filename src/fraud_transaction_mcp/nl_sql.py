"""Natural language -> SQL -> Databricks SQL warehouse, exposed as an MCP tool.

Flow: question -> LLM (LLM_ENDPOINT: UC model service via AI Gateway, or a
serving endpoint) generates one
read-only SELECT over the configured transaction table -> SQL is validated
(sqlglot parse: single SELECT/WITH, only the allowed table, no DDL/DML, no labels) -> wrapped in a row
LIMIT -> executed through the backend (SQL warehouse) -> rows returned.

Defense in depth: the app service principal only has SELECT on the table.
"""
import json
import re

from .config import get_settings
from .models import COLUMNS
from .sql_guard import validate_select


# UC model service (catalog.schema.name) is called through AI Gateway;
# a plain serving endpoint name is called through /serving-endpoints.
# The default endpoint lives in config.Settings.llm_endpoint (env LLM_ENDPOINT).
def _endpoint():
    return get_settings().llm_endpoint


def _system_prompt(table):
    cols = '\n'.join(f'- {n} ({t}): {d}' for n, t, d in COLUMNS)
    return (
        'You translate questions about credit card transactions into ONE Databricks SQL query.\n'
        f'The only table you may use is {table} with columns:\n{cols}\n\n'
        'Rules:\n'
        '- Return exactly one read-only SELECT (CTEs with WITH are allowed). No DDL/DML, no semicolons.\n'
        f'- Reference only {table} (always fully qualified). No other tables, files, or functions that read external data.\n'
        '- Use Databricks SQL syntax (e.g. date_trunc, year(), date_format).\n'
        '- Prefer aggregates; when listing rows, ORDER BY something meaningful and LIMIT 100 or less.\n'
        '- There is no fraud label in this table; if asked about fraud, set sql to null and explain.\n'
        'Respond with JSON only: {"sql": "<query or null>", "explanation": "<one sentence>"}'
    )


def _call_llm(question, table):
    from databricks.sdk import WorkspaceClient
    w = WorkspaceClient()
    body = {'messages': [
        {'role': 'system', 'content': _system_prompt(table)},
        {'role': 'user', 'content': question}]}
    model = _endpoint()
    if '.' in model:
        body['model'] = model
        resp = w.api_client.do('POST', '/ai-gateway/mlflow/v1/chat/completions', body=body)
    else:
        resp = w.api_client.do('POST', f'/serving-endpoints/{model}/invocations', body=body)
    content = resp['choices'][0]['message']['content']
    if isinstance(content, list):  # some models return content parts
        content = ''.join(p.get('text', '') for p in content if isinstance(p, dict))
    return content


def _parse(content):
    text = content.strip()
    m = re.search(r'\{.*\}', text, re.DOTALL)
    if not m:
        raise ValueError('Model did not return JSON')
    data = json.loads(m.group(0))
    return data.get('sql'), data.get('explanation', '')


def validate_sql(sql, table):
    """Validate LLM SQL (see sql_guard.validate_select)."""
    return validate_select(sql, table)


def enforce_limit(sql, max_rows):
    """Cap rows while keeping the query's own ORDER BY: tighten a trailing LIMIT or append one."""
    m = re.search(r'\bLIMIT\s+(\d+)\s*$', sql, re.IGNORECASE)
    if m:
        return sql[:m.start()] + f'LIMIT {min(int(m.group(1)), max_rows)}'
    return f'{sql} LIMIT {max_rows}'


def ask_transactions(backend, question, limit=50):
    if not isinstance(question, str) or not question.strip() or len(question) > 2000:
        raise ValueError('question must be a nonempty string <= 2000 characters')
    if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= 200:
        raise ValueError('limit must be an integer between 1 and 200')
    table = backend.transactions
    sql, explanation = _parse(_call_llm(question.strip(), table))
    if not sql:
        return {'question': question, 'sql': None, 'explanation': explanation, 'records': [],
                'model_endpoint': _endpoint()}
    sql = validate_sql(sql, table)
    rows = backend.query(enforce_limit(sql, limit + 1))
    return {'question': question, 'sql': sql, 'explanation': explanation,
            'records': rows[:limit], 'returned': min(len(rows), limit),
            'truncated': len(rows) > limit, 'model_endpoint': _endpoint(),
            'note': 'SQL was generated by an LLM and validated as read-only; verify important results.'}
